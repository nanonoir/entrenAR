/**
 * Builds `src/lib/data/locations/cp4-province-table.generated.ts` from the GeoNames Argentina postal code dump
 * (https://download.geonames.org/export/zip/AR.zip, CC BY 4.0, https://www.geonames.org).
 *
 * Run manually after extracting the zip into an empty directory: `npx tsx scripts/generate-cp4-province-table.ts <path-to-AR.txt>`.
 * Only CP4 values whose every GeoNames row belongs to ONE province are kept; multi-province values are counted and
 * left out (unknown/ambiguous never blocks the shopper). No ranges are inferred. The app never calls GeoNames at runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** GeoNames admin1 name (as published) → Georef province id. Capital Federal is not part of the GeoNames AR dump. */
const PROVINCE_IDS: Readonly<Record<string, string>> = {
  "Buenos Aires": "06", Catamarca: "10", Chaco: "22", Chubut: "26", Cordoba: "14", Corrientes: "18", "Entre Rios": "30",
  Formosa: "34", Jujuy: "38", "La Pampa": "42", "La Rioja": "46", Mendoza: "50", Misiones: "54", Neuquen: "58",
  "Rio Negro": "62", Salta: "66", "San Juan": "70", "San Luis": "74", "Santa Cruz": "78", "Santa Fe": "82",
  "Santiago Del Estero": "86", "Tierra Del Fuego": "94", Tucuman: "90",
};

const source = process.argv[2];
if (!source) throw new Error("Usage: npx tsx scripts/generate-cp4-province-table.ts <path-to-AR.txt>");

const provincesByCode = new Map<string, Set<string>>();
let rowCount = 0;
for (const line of readFileSync(source, "utf8").split("\n")) {
  if (!line.trim()) continue;
  const columns = line.split("\t");
  const code = columns[1]?.trim() ?? "";
  const provinceId = PROVINCE_IDS[columns[3]?.trim() ?? ""];
  if (!/^[1-9]\d{3}$/.test(code)) continue;
  if (!provinceId) throw new Error(`Unmapped GeoNames province "${columns[3]}" for ${code}`);
  rowCount += 1;
  provincesByCode.set(code, (provincesByCode.get(code) ?? new Set()).add(provinceId));
}

const unique = [...provincesByCode].filter(([, ids]) => ids.size === 1).sort(([left], [right]) => left.localeCompare(right));
const ambiguous = provincesByCode.size - unique.length;
const body = unique.map(([code, ids]) => `  "${code}": "${[...ids][0]}",`).join("\n");

writeFileSync(
  join(process.cwd(), "src", "lib", "data", "locations", "cp4-province-table.generated.ts"),
  `// Generated by scripts/generate-cp4-province-table.ts — do not edit by hand.
// Source: GeoNames postal codes for Argentina (AR.zip), CC BY 4.0, https://www.geonames.org.
// Rows read: ${rowCount}. Distinct CP4: ${provincesByCode.size}. Single-province (kept): ${unique.length}. Multi-province (omitted): ${ambiguous}.
// Not covered: Ciudad Autónoma de Buenos Aires (absent from the dump) and any CP4 missing from GeoNames.
export const CP4_PROVINCE_TABLE_SOURCE = "GeoNames AR postal codes (CC BY 4.0)";
export const CP4_PROVINCE_TABLE_STATS = { distinct: ${provincesByCode.size}, multiProvinceOmitted: ${ambiguous}, recognized: ${unique.length} } as const;

/** CP4 → Georef province id, only for CP4 values whose every GeoNames entry belongs to a single province. */
export const CP4_PROVINCE_TABLE: Readonly<Record<string, string>> = {
${body}
};
`,
);
console.log(`Wrote ${unique.length} single-province CP4 values (${ambiguous} multi-province omitted, ${provincesByCode.size} distinct).`);
